"""Small local reference library for MiniMax H3 per-project shots.

H3 reference-to-video is EXCLUSIVE with first/last-frame I2V. Only projects
explicitly selecting reference mode use these assets. A storyboard image is
then treated as reference_image, not a frame locked at video time zero.
Media is stored locally and supplied as bounded data URIs on paid submission.
No public file hosting, URL fetching, or external credential sharing.
"""
import hashlib
import io
import json
import os
import re
import threading
import uuid
import wave
from pathlib import Path

from PIL import Image, UnidentifiedImageError

from src.config import Config
from src.text.ip_library import project_ip

_LOCK = threading.RLock()
_ID = re.compile(r"^[A-Za-z0-9_-]{1,100}$")
_SCENE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
_IMAGE_UPLOAD_LIMIT = 12 * 1024 * 1024
_AUDIO_UPLOAD_LIMIT = 8 * 1024 * 1024


class H3ReferenceError(ValueError):
    pass


def _project_dir(task_id):
    if not _ID.fullmatch(str(task_id)):
        raise H3ReferenceError("非法项目 ID")
    # Keep reference voice/character assets OUTSIDE the public /media route.
    return Config.BASE_DIR / "data" / "_private" / "h3_references" / str(task_id)


def _config_path(task_id):
    return _project_dir(task_id) / "reference_settings.json"


def _read(task_id):
    # Validate the task ID outside the exception handler: H3ReferenceError
    # extends ValueError and must never be disguised as "no settings".
    path = _config_path(task_id)
    try:
        item = json.loads(path.read_text("utf-8"))
        return item if isinstance(item, dict) else {}
    except (OSError, ValueError):
        return {}


def _commit(task_id, settings):
    path = _config_path(task_id)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(f".{path.name}.{uuid.uuid4().hex}.tmp")
    try:
        temp.write_text(json.dumps(settings, ensure_ascii=False), encoding="utf-8")
        os.replace(temp, path)
    finally:
        temp.unlink(missing_ok=True)


def mode(task_id):
    return "reference" if _read(task_id).get("mode") == "reference" else "first_frame"


def _image_path(task_id, filename):
    # Filenames are generated by us, NEVER accepted from the user.
    if not isinstance(filename, str) or not re.fullmatch(r"[A-Za-z0-9_-]+\.(?:jpg|wav)", filename):
        return None
    root = _project_dir(task_id)
    return root / filename


def _asset(task_id, name):
    path = _image_path(task_id, name)
    return path if path and path.is_file() else None


def _scene(scene_id):
    if not _SCENE.fullmatch(str(scene_id)):
        raise H3ReferenceError("非法场景 ID")
    return str(scene_id)


def _fingerprint(path):
    data = Path(path).read_bytes()
    return hashlib.sha256(data).hexdigest()


def overview(task_id, scene_ids=()):
    config = _read(task_id)
    profile = project_ip(task_id) or {}
    ip_ref = Path(profile["reference_image"]) if profile.get("reference_image") else None
    ip_ready = bool(ip_ref and ip_ref.is_file())
    scene_images = config.get("scenes") or {}
    return {
        "mode": mode(task_id),
        "ip_ready": ip_ready,
        "ip_name": profile.get("name") if ip_ready else None,
        "voice_ready": bool(_asset(task_id, config.get("voice"))),
        "scenes": [{
            "scene_id": key,
            "image_ready": bool(_asset(task_id, scene_images.get(key))),
        } for key in dict.fromkeys(scene_ids) if _SCENE.fullmatch(str(key))],
        "note": (
            "参考生成不会锁定视频第一帧；仅提高角色、场景与音色相似度。"
            "声音参考并不保证对白内容或字幕完全一致。"
        ),
    }


def select_mode(task_id, value):
    if value not in {"first_frame", "reference"}:
        raise H3ReferenceError("只能选择首帧图生视频或 H3 多模态参考模式")
    with _LOCK:
        config = _read(task_id)
        config["mode"] = value
        _commit(task_id, config)
    return value


def save_scene_image(task_id, scene_id, data):
    scene_id = _scene(scene_id)
    if not data or len(data) > _IMAGE_UPLOAD_LIMIT:
        raise H3ReferenceError("场景图片不得超过 12 MB")
    try:
        with Image.open(io.BytesIO(data)) as im:
            im.verify()
        with Image.open(io.BytesIO(data)) as im:
            if im.format not in {"JPEG", "PNG", "WEBP"}:
                raise H3ReferenceError("场景参考仅支持 JPEG、PNG、WebP")
            w, h = im.size
            if not (256 <= w <= 5760 and 256 <= h <= 5760 and 0.4 <= w / h <= 2.5):
                raise H3ReferenceError("H3 场景参考图边长需为 256–5760 像素，宽高比 0.4–2.5")
            im.load()
            output = io.BytesIO()
            # Keep uploaded references small enough for data-URI requests.
            im.convert("RGB").save(output, "JPEG", quality=86, optimize=True)
            encoded = output.getvalue()
            if len(encoded) > _IMAGE_UPLOAD_LIMIT:
                raise H3ReferenceError("压缩后的参考图过大")
    except (UnidentifiedImageError, OSError, Image.DecompressionBombError):
        raise H3ReferenceError("场景参考图片损坏或不安全") from None
    with _LOCK:
        folder = _project_dir(task_id)
        folder.mkdir(parents=True, exist_ok=True)
        name = f"scene_{uuid.uuid4().hex}.jpg"
        (folder / name).write_bytes(encoded)
        settings = _read(task_id)
        scenes = dict(settings.get("scenes") or {})
        scenes[scene_id] = name
        settings["scenes"] = scenes
        _commit(task_id, settings)
    return {"scene_id": scene_id, "image_ready": True}


def save_voice_sample(task_id, data):
    if not data or len(data) > _AUDIO_UPLOAD_LIMIT:
        raise H3ReferenceError("声音参考 WAV 不得超过 8 MB")
    try:
        with wave.open(io.BytesIO(data), "rb") as handle:
            if handle.getcomptype() != "NONE" or handle.getnchannels() not in {1, 2}:
                raise H3ReferenceError("仅支持单/双声道未压缩 PCM WAV")
            if handle.getframerate() <= 0 or handle.getsampwidth() not in {1, 2, 3, 4}:
                raise H3ReferenceError("WAV 参数不支持")
            seconds = handle.getnframes() / handle.getframerate()
            if not (2 <= seconds <= 15):
                raise H3ReferenceError("声音样本时长须为 2–15 秒")
            if len(handle.readframes(handle.getnframes())) != (
                handle.getnframes() * handle.getnchannels() * handle.getsampwidth()
            ):
                raise H3ReferenceError("WAV 音频内容不完整")
    except (wave.Error, EOFError, OSError):
        raise H3ReferenceError("无效的 PCM WAV 音频") from None
    with _LOCK:
        folder = _project_dir(task_id)
        folder.mkdir(parents=True, exist_ok=True)
        name = f"voice_{uuid.uuid4().hex}.wav"
        (folder / name).write_bytes(data)
        settings = _read(task_id)
        settings["voice"] = name
        _commit(task_id, settings)
    return {"voice_ready": True, "duration_seconds": round(seconds, 2)}


def clear_voice(task_id):
    with _LOCK:
        config = _read(task_id)
        config.pop("voice", None)
        _commit(task_id, config)


def clear_scene(task_id, scene_id):
    scene_id = _scene(scene_id)
    with _LOCK:
        config = _read(task_id)
        scenes = dict(config.get("scenes") or {})
        scenes.pop(scene_id, None)
        config["scenes"] = scenes
        _commit(task_id, config)


def for_shot(task_id, shot_frame, scene_id):
    """Return immutable file names + content digests for a single shot.

    The snapshot makes clip reuse reference-aware. Later uploads never alter
    already approved paid requests; they create a new fingerprint.
    """
    if mode(task_id) != "reference":
        return None
    settings = _read(task_id)
    images = [str(Path(shot_frame).resolve())]
    profile = project_ip(task_id) or {}
    ip = Path(profile["reference_image"]) if profile.get("reference_image") else None
    if ip and not ip.is_file():
        raise H3ReferenceError("绑定 IP 的参考图已丢失，请修复或创建新项目")
    if ip:
        images.append(str(ip.resolve()))
    scene_name = (settings.get("scenes") or {}).get(scene_id)
    scene = _asset(task_id, scene_name)
    if scene_name and not scene:
        raise H3ReferenceError("场景参考图片已丢失，请重新上传")
    if scene:
        images.append(str(scene.resolve()))
    # No duplicate images. First image is current shot composition reference;
    # the following references lock IP and scene without a first_frame role.
    images = list(dict.fromkeys(images))
    if len(images) > 9:
        raise H3ReferenceError("H3 最多允许 9 张参考图片")
    voice = _asset(task_id, settings.get("voice"))
    if settings.get("voice") and not voice:
        raise H3ReferenceError("音色参考已丢失，请重新上传")
    audio = str(voice.resolve()) if voice else None
    try:
        digests = [_fingerprint(path) for path in images]
        if audio:
            digests.append(_fingerprint(audio))
    except OSError:
        raise H3ReferenceError("参考素材已丢失，请重新上传后再提交任务") from None
    # Including reference paths is internal only; do not send it to browsers.
    snapshot = {
        "mode": "reference", "images": images, "audio": audio,
        "digests": digests,
    }
    snapshot["fingerprint"] = hashlib.sha256(
        json.dumps({"files": digests, "mode": "reference"}, sort_keys=True).encode()
    ).hexdigest()
    return snapshot


def fingerprint_now(task_id, shot_frame, scene_id):
    item = for_shot(task_id, shot_frame, scene_id)
    return item["fingerprint"] if item else "first_frame"
